const serviceOptions = document.getElementById("service-type-options");
const weightBlock = document.getElementById("laundry-weight-block");
const weightOptions = document.getElementById("weight-options");
const ironingBlock = document.getElementById("laundry-ironing-block");
const ironingClothSelect = document.getElementById("ironing-cloth-type");
const laundryAmountBar = document.getElementById("laundry-amount-bar");
const laundryAmountEl = document.getElementById("laundry-amount");
const laundryFormError = document.getElementById("laundry-form-error");
const btnGenerateLaundryToken = document.getElementById("btn-generate-laundry-token");

serviceOptions.addEventListener("click", (e) => {
  const btn = e.target.closest(".option-btn");
  if (!btn) return;

  laundrySelection.service = btn.dataset.service;
  laundrySelection.weight = null;

  [...serviceOptions.children].forEach((b) => b.classList.toggle("selected", b === btn));
  [...weightOptions.children].forEach((b) => b.classList.remove("selected"));

  const needsWeight = laundrySelection.service === "Wash Only" || laundrySelection.service === "Wash & Dry";
  const needsIroning = laundrySelection.service === "Ironing";

  weightBlock.hidden = !needsWeight;
  ironingBlock.hidden = !needsIroning;

  updateLaundryAmount();
});

weightOptions.addEventListener("click", (e) => {
  const btn = e.target.closest(".option-btn");
  if (!btn) return;
  laundrySelection.weight = btn.dataset.weight;
  [...weightOptions.children].forEach((b) => b.classList.toggle("selected", b === btn));
  updateLaundryAmount();
});

ironingClothSelect.addEventListener("change", () => {
  laundrySelection.clothType = ironingClothSelect.value;
});

document.getElementById("iron-qty-minus").addEventListener("click", () => {
  laundrySelection.quantity = Math.max(1, laundrySelection.quantity - 1);
  document.getElementById("iron-qty-value").textContent = laundrySelection.quantity;
  updateLaundryAmount();
});
document.getElementById("iron-qty-plus").addEventListener("click", () => {
  laundrySelection.quantity = Math.min(50, laundrySelection.quantity + 1);
  document.getElementById("iron-qty-value").textContent = laundrySelection.quantity;
  updateLaundryAmount();
});

function calculateLaundryAmount() {
  const { service, weight, quantity } = laundrySelection;
  if (!service) return 0;
  if (service === "Ironing") {
    return PRICING.Ironing.perCloth * quantity;
  }
  if (!weight) return 0;
  return (PRICING[service] && PRICING[service][weight]) || 0;
}

function isLaundrySelectionValid() {
  if (!laundrySelection.service) return false;
  if (laundrySelection.service === "Ironing") return laundrySelection.quantity > 0;
  return !!laundrySelection.weight;
}

function updateLaundryAmount() {
  const valid = isLaundrySelectionValid();
  const amount = calculateLaundryAmount();

  laundryAmountBar.hidden = !valid;
  laundryAmountEl.textContent = rupees(amount);
  btnGenerateLaundryToken.disabled = !valid;
  laundryFormError.textContent = "";
}

function resetLaundryForm() {
  laundrySelection = { service: null, weight: null, clothType: "Shirt", quantity: 1 };
  [...serviceOptions.children].forEach((b) => b.classList.remove("selected"));
  [...weightOptions.children].forEach((b) => b.classList.remove("selected"));
  weightBlock.hidden = true;
  ironingBlock.hidden = true;
  ironingClothSelect.value = "Shirt";
  document.getElementById("iron-qty-value").textContent = "1";
  laundryAmountBar.hidden = true;
  laundryAmountEl.textContent = "0";
  btnGenerateLaundryToken.disabled = true;
  laundryFormError.textContent = "";
}

btnGenerateLaundryToken.addEventListener("click", () => {
  if (!isLaundrySelectionValid()) {
    laundryFormError.textContent = "Please complete the service details before generating a token.";
    return;
  }

  const amount = calculateLaundryAmount();
  const { date, time, label } = formatDateTime();
  const isIroning = laundrySelection.service === "Ironing";

  const txn = {
    id: `LDY-${laundryTokenSeq++}`,
    type: "Laundry",
    service: laundrySelection.service,
    weight: isIroning ? null : laundrySelection.weight,
    clothType: isIroning ? laundrySelection.clothType : null,
    quantity: isIroning ? laundrySelection.quantity : null,
    amount,
    status: "Waiting for Verification",
    date,
    time,
    dateTimeLabel: label,
    remainingBalance: null,
  };

  transactions.unshift(txn);
  resetLaundryForm();
  showTokenSheet(txn);
  renderAll();
});

