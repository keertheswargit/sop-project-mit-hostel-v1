function searchStaffToken() {
  const raw = document.getElementById("staff-token-input").value.trim().toUpperCase();
  const errorEl = document.getElementById("staff-search-error");
  const resultEl = document.getElementById("staff-result");

  if (!raw) {
    errorEl.textContent = "Please enter a token number.";
    resultEl.hidden = true;
    staffActiveTokenId = null;
    return;
  }

  const txn = transactions.find((t) => t.id === raw);

  if (!txn) {
    errorEl.textContent = "Token not found.";
    resultEl.hidden = true;
    staffActiveTokenId = null;
    return;
  }

  if (txn.status !== "Waiting for Verification") {
    errorEl.textContent = `This token has already been ${txn.status.toLowerCase()}.`;
    resultEl.hidden = true;
    staffActiveTokenId = null;
    return;
  }

  errorEl.textContent = "";
  staffActiveTokenId = txn.id;
  populateStaffResult(txn);
  resultEl.hidden = false;
}

function populateStaffResult(txn) {
  document.getElementById("staff-result-token").textContent = txn.id;
  document.getElementById("staff-result-name").textContent = student.name;
  document.getElementById("staff-result-regno").textContent = student.regNo;
  document.getElementById("staff-result-type").textContent = txn.type;
  document.getElementById("staff-result-service").textContent = txn.service;

  const weightRow = document.getElementById("staff-result-weight-row");
  const clothRow = document.getElementById("staff-result-cloth-row");

  if (txn.weight) {
    weightRow.hidden = false;
    document.getElementById("staff-result-weight").textContent = txn.weight;
  } else {
    weightRow.hidden = true;
  }

  if (txn.clothType) {
    clothRow.hidden = false;
    document.getElementById("staff-result-cloth").textContent = `${txn.clothType} × ${txn.quantity}`;
  } else {
    clothRow.hidden = true;
  }

  document.getElementById("staff-result-amount").textContent = `₹${rupees(txn.amount)}`;
  document.getElementById("staff-result-balance").textContent = `₹${rupees(wallet.balance)}`;
  document.getElementById("staff-result-status").textContent = txn.status;
}

document.getElementById("btn-confirm-transaction").addEventListener("click", () => {
  const errorEl = document.getElementById("staff-search-error");
  const txn = transactions.find((t) => t.id === staffActiveTokenId);

  if (!txn) {
    errorEl.textContent = "Token not found. Please search again.";
    document.getElementById("staff-result").hidden = true;
    return;
  }

  if (txn.status !== "Waiting for Verification") {
    errorEl.textContent = `This token has already been ${txn.status.toLowerCase()}.`;
    document.getElementById("staff-result").hidden = true;
    return;
  }

  if (wallet.balance < txn.amount) {
    errorEl.textContent = "Insufficient wallet balance. Transaction cannot be confirmed.";
    return;
  }

  wallet.balance -= txn.amount;
  wallet.totalSpent += txn.amount;
  wallet.count += 1;

  txn.status = "Confirmed";
  txn.remainingBalance = wallet.balance;

  document.getElementById("staff-result").hidden = true;
  document.getElementById("staff-token-input").value = "";
  errorEl.textContent = "";
  staffActiveTokenId = null;

  showToast(`Transaction ${txn.id} confirmed — ₹${rupees(txn.amount)} deducted`);
  renderAll();
});

