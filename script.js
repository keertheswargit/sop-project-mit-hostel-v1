/* ---------------------- 15. TRANSACTION HISTORY ---------------------- */

function renderHistory() {
  document.getElementById("stat-balance").textContent = rupees(wallet.balance);
  document.getElementById("stat-spent").textContent = rupees(wallet.totalSpent);
  document.getElementById("stat-count").textContent = wallet.count;

  const list = document.getElementById("history-list");
  list.innerHTML = "";

  if (transactions.length === 0) {
    const wrap = document.createElement("div");
    wrap.className = "timeline-item";
    wrap.innerHTML = `
      <span class="timeline-dot"></span>
      <div class="timeline-card">
        <div><p class="timeline-date">No transactions yet</p><p class="timeline-sub">Generate a laundry or store token to get started</p></div>
      </div>
    `;
    list.appendChild(wrap);
    return;
  }

  transactions.forEach((txn) => list.appendChild(buildHistoryItem(txn)));
}

function buildHistoryItem(txn) {
  const wrap = document.createElement("div");
  wrap.className = "timeline-item";

  const statusClass = txn.status === "Confirmed" ? "confirmed" : "waiting";
  const metaParts = [];
  if (txn.weight) metaParts.push(`<span>Weight <b>${txn.weight}</b></span>`);
  if (txn.clothType) metaParts.push(`<span>Cloth <b>${txn.clothType} × ${txn.quantity}</b></span>`);
  metaParts.push(`<span>${txn.date} <b>${txn.time}</b></span>`);

  const remainingLabel = txn.remainingBalance !== null ? `₹${rupees(txn.remainingBalance)}` : "—";

  wrap.innerHTML = `
    <span class="timeline-dot"></span>
    <div class="timeline-card txn-card">
      <div class="txn-card-top">
        <span class="txn-token">${txn.id} · ${txn.type}</span>
        <span class="status-chip ${statusClass}">${txn.status}</span>
      </div>
      <p class="timeline-sub">${txn.service}</p>
      <div class="txn-meta">${metaParts.join("")}</div>
      <div class="txn-bottom">
        <span class="txn-amount">₹${rupees(txn.amount)}</span>
        <span class="mini-item-sub">Remaining: ${remainingLabel}</span>
      </div>
    </div>
  `;
  return wrap;
}

/* ---------------------- 16. STAFF VERIFICATION ---------------------- */

document.getElementById("btn-staff-search").addEventListener("click", searchStaffToken);
